package com.example.myfirstapp.ui.home

/**
 * 每日名言：本地内置一批旅行 / 户外主题的名言，
 * 按"距纪元天数"确定性取一条 —— 同一天不变、跨天自动切换，无需联网。
 *
 * 之所以本地内置而非走服务器：名言是首页氛围点缀，不应因服务器未启动而缺失，
 * 本地确定算法保证"每天一条且稳定"，也避免每次刷新跳动。
