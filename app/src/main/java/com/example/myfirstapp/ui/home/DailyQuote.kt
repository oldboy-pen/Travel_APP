    /** 今天该显示的名言（同一天恒定，跨天切换） */
    fun today(): Quote {
        val dayIndex = (System.currentTimeMillis() / 86_400_000L).toInt()
        val idx = (dayIndex % QUOTES.size + QUOTES.size) % QUOTES.size
        return QUOTES[idx]
    }
}
